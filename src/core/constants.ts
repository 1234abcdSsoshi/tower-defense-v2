/* =====================================================================
   どのレイヤーからも参照される定数。ここには「値」だけを置き、
   マスタデータから来る可変の値（BAL.* 等）は絶対に混ぜない。
   ===================================================================== */

/** シミュレーションの固定タイムステップ。決定論を保つため実時間には決して追従させない */
export const DT = 1 / 60;

/** 戦場の論理幅。描画スケール SC はこの幅を画面幅へ写す倍率 */
export const WORLD_W = 800;
/** 地面の高さ（画面高に対する比） */
export const GROUND_R = 0.715;

/* 画面に出る1分 = 中の30秒（標準速度は中の時計の半分で進むため）。
   保存するのは中の秒数で、0 は「無制限」。 */
export const MIN_UNIT = 30;

/** 入力ログの形式。上げると古いゴーストは捨てられる */
export const REC_V = 6;

/* 標準の進行を従来の半分にして、そこから 1／2／4／8 倍を選べるようにする。
   表示の x1 が「従来の半分」、x2 が「従来の標準」にあたる。 */
export const SPD_BASE = 0.5;
export const SPD_OPTS = [1, 2, 4, 8] as const;

/* 画面に出す秒は「標準速度で見たときの秒」に直す。
   標準は従来の半分の速さで進むので、中の1秒は画面の2秒にあたる。
   こうすると x1 では時計がきっちり1秒に1つ進み、倍速では見た目どおり倍の速さで進む。 */
export const DSEC = 1 / SPD_BASE;

/** localStorage のキー。変えると全ユーザーの進行が消えるので、移行処理なしに触らないこと */
export const SAVE_KEY = "jidai.save";
export const SAVE_V = 3;
export const CFG_KEY = "jidai.cfg";
